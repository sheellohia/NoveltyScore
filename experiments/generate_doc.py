    w(f"Baseline Spearman (every row's reference): {f(R(ladder[0]['name'], 'spearman_mean'))}.")
    w("")
    w("### Embedding × combine × gate sweep")
    w("")
    w(table(["config"] + [c[0] for c in cols],
            [[c["name"]] + [f(R(c["name"], k), s) for _, k, s in cols] for c in matrix]))
    w("")
    win = exp["winner"]
    req = [c for c in matrix if c["group"] == "matrix" and c["metrics"]["spearman_mean"] is not None]
    best_req = max(req, key=lambda c: c["metrics"]["spearman_mean"]) if req else None
    w(f"Winner by mean per-topic Spearman over all 5 topics: **{win['name']}** ({f(win.get('spearman_mean'))}). "
      f"LOTO held-out Spearman of the selection procedure: {f(loto.get('held_out_spearman_mean'))}. "
      f"Best of the {len(req)} requested MiniLM/mpnet configurations alone: "
      f"{best_req['name'] if best_req else NM} ({f(best_req['metrics']['spearman_mean'] if best_req else None)}).")
    w("")
    w("### Gate sensitivity (full system; not used for selection)")
    w("")
    w(table(["floor margin / gate target at on-topic p5"] + [c[0] for c in cols] + ["on-topic gate ≥ 0.9"],
            [[f"{c['floor_margin']} / {c['gate_target']}"] + [f(R(c["name"], k), s) for _, k, s in cols]
             + [pct(R(c["name"], "on_topic_gate_coverage"))] for c in sens]))
    w("")
    w(src("results/summary.csv"))
    w("")

    # 7 -------------------------------------------------------------------
    sp = [c["metrics"]["spearman_mean"] for c in sens if c["metrics"]["spearman_mean"] is not None]
    t2 = [c["metrics"]["t2_max"] for c in sens if c["metrics"]["t2_max"] is not None]
    other_t2 = {c["embedding"]: c["metrics"]["t2_max"] for c in matrix if c["gate"] == "asymmetric" and c["combine"] == "rankfusion"}
    w("## 7. Limitations & future work")
    w("")
    n_cases = sorted({len(v["cases"]) for v in pt.values()})
    lo, hi = min(meta["topics"].values()), max(meta["topics"].values())
