"""Generate SOLUTION.md (and SOLUTION.pdf if a converter exists) from results/*.

Usage (from repo root):
    backend/.venv/bin/python experiments/generate_doc.py

Every number in the document is read from results/experiments.json,
results/summary.csv or results/criteria_report.json. Anything missing is
written as "not measured". Prose that makes a directional claim ("raised",
"lowered") picks its wording from the sign of the recorded delta.
"""

import csv
import json
import shutil
import subprocess
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
RES = REPO / "results"
OUT = REPO / "SOLUTION.md"
NM = "not measured"


# ---------------------------------------------------------------------------
def load():
    exp = json.loads((RES / "experiments.json").read_text())
    crit = json.loads((RES / "criteria_report.json").read_text())
    rows = {}
    with (RES / "summary.csv").open() as f:
        for r in csv.DictReader(f):
            rows[r["name"]] = {k: _num(v) for k, v in r.items()}
    return exp, crit, rows


def _num(v):
    if v in ("", None):
        return None
    try:
        return float(v)
    except ValueError:
        return v


def f(x, spec=".3f"):
    if x is None:
        return NM
    if isinstance(x, bool):
        return "yes" if x else "no"
    if isinstance(x, (int, float)):
        return format(x, spec)
    return str(x)


def pct(x):
    return NM if x is None else f"{x:.0%}"


def delta(a, b, spec="+.3f"):
    return NM if a is None or b is None else format(b - a, spec)


def direction(a, b, up="raised", down="lowered", same="did not change", eps=5e-4):
    if a is None or b is None:
        return "could not be compared (not measured)"
    d = b - a
    return same if abs(d) < eps else (up if d > 0 else down)


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    esc = lambda c: str(c).replace("|", "\\|")
    out[0] = "| " + " | ".join(esc(h) for h in header) + " |"
    out += ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def src(path):
    return f"<sub>source: `{path}`</sub>"


